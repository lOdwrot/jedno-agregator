/**
 * Renders the drawn card pictures of "Walka o duszę" to `public/soul/art/<id>.webp`.
 *   npx tsx scripts/soul-art/render.ts            # every drawn card
 *   npx tsx scripts/soul-art/render.ts lektor ... # only these
 *   (a full run also rewrites src/features/games/soul/data/drawnArt.ts)
 *   SHEET=1 npx tsx scripts/soul-art/render.ts    # also writes a contact sheet to soul-art-sheet.png
 * Every scene also gets two layers for the album's parallax: `bg/<id>.webp` (backdrop only) and
 * `fg/<id>.webp` (the motif on a transparent background).
 * Uses the Playwright Chromium (PW_CHROMIUM_PATH overrides the binary).
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { chromium } from "playwright";
import { H, W } from "./kit";
import { SCENES } from "./scenes";

const OUT = resolve(import.meta.dirname, "../../public/soul/art");
const only = process.argv.slice(2);
const ids = Object.keys(SCENES).filter((id) => !only.length || only.includes(id));

const browser = await chromium.launch(
  process.env.PW_CHROMIUM_PATH ? { executablePath: process.env.PW_CHROMIUM_PATH } : {},
);
const page = await browser.newPage();
await page.setContent("<html><body></body></html>");
mkdirSync(`${OUT}/bg`, { recursive: true });
mkdirSync(`${OUT}/fg`, { recursive: true });

const encode = (svg: string, type: string, q: number) =>
  page.evaluate(
    async ({ svg, w, h, type, q }) => {
      const img = new Image();
      img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
      await img.decode();
      const c = document.createElement("canvas");
      c.width = w;
      c.height = h;
      c.getContext("2d")!.drawImage(img, 0, 0, w, h);
      return c.toDataURL(type, q).split(",")[1]!;
    },
    { svg, w: W, h: H, type, q },
  );

for (const id of ids) {
  const svg = SCENES[id]!();
  writeFileSync(`${OUT}/${id}.webp`, Buffer.from(await encode(svg, "image/webp", 0.82), "base64"));
  const layers = SCENES[id]!.layers;
  if (layers) {
    // the backdrop is mostly soft gradients: a lower quality is enough
    const bg = await encode(layers.bg(), "image/webp", 0.6);
    writeFileSync(`${OUT}/bg/${id}.webp`, Buffer.from(bg, "base64"));
    const fg = await encode(layers.fg(), "image/webp", 0.82);
    writeFileSync(`${OUT}/fg/${id}.webp`, Buffer.from(fg, "base64"));
  }
}
console.log(`rendered ${ids.length} pictures`);
if (!only.length) {
  const list = Object.keys(SCENES)
    .sort()
    .map((id) => `  "${id}",`)
    .join("\n");
  writeFileSync(
    resolve(import.meta.dirname, "../../src/features/games/soul/data/drawnArt.ts"),
    `/** Cards with a picture drawn for the game (generated by scripts/soul-art/render.ts — do not edit). */\nexport const DRAWN_ART: ReadonlySet<string> = new Set([\n${list}\n]);\n`,
  );
}

if (process.env.SHEET) {
  const cols = 8;
  const tw = 300;
  const th = 225;
  const cells = await Promise.all(
    ids.map(async (id) => ({
      id,
      src: `data:image/svg+xml;charset=utf-8,${encodeURIComponent(SCENES[id]!())}`,
    })),
  );
  const html = `<html><body style="margin:0;background:#222;display:grid;grid-template-columns:repeat(${cols},${tw}px);gap:4px;font:12px sans-serif;color:#fff">${cells
    .map(
      (c) =>
        `<div><img src="${c.src}" width="${tw}" height="${th}" style="display:block"/>${c.id}</div>`,
    )
    .join("")}</body></html>`;
  await page.setViewportSize({ width: cols * (tw + 4), height: 800 });
  await page.setContent(html);
  await page.screenshot({
    path: process.env.SHEET === "1" ? "soul-art-sheet.png" : process.env.SHEET,
    fullPage: true,
  });
}
await browser.close();
